static const glyph *find_glyph(char c)
{
    size_t i;
    char u = (char)toupper((unsigned char)c);

    for (i = 0; i < sizeof GLYPHS / sizeof GLYPHS[0]; i++)
        if (GLYPHS[i].ch == u)
            return &GLYPHS[i];
    return NULL;
}

void font_draw(SDL_Renderer *r, int x, int y, int scale, const char *s)
{
    const glyph *g;
    SDL_Rect px;
    int row, col;

    px.w = scale;
    px.h = scale;
    for (; *s; s++, x += FONT_ADVANCE * scale) {
        g = find_glyph(*s);
        if (!g)
            continue;
        for (row = 0; row < FONT_GLYPH_H; row++) {
            for (col = 0; col < FONT_GLYPH_W; col++) {
                if (!(g->rows[row] & (0x10 >> col)))
                    continue;
                px.x = x + col * scale;
                px.y = y + row * scale;
                SDL_RenderFillRect(r, &px);
            }
        }
    }
}

int font_text_width(const char *s, int scale)
{
    size_t n = strlen(s);

    if (n == 0)
        return 0;
    /* no trailing spacing column after the last glyph */
    return (int)n * FONT_ADVANCE * scale - scale;
}
